"""Checkpoint-backed mechanical inference checks; no accuracy claim."""
import math

import numpy as np
import pytest


def test_actual_pretrained_inference():
    from ml.service import ModelService
    service = ModelService()
    signal = (0.08 * np.sin(2 * np.pi * 220 * np.arange(32000) / 16000)).astype(np.float32)
    result = service.analyze(signal, sample_rate=16000)
    assert math.isfinite(result['score'])
    assert 0 <= result['score'] <= 1
    assert result['classification'] == 'uncertain', 'Unvalidated thresholds must not imply confidence'
    assert result['segments']
    for segment in result['segments']:
        assert 0 <= segment['start'] < segment['end'] <= 2.001
        assert math.isfinite(segment['score'])
    repeated = service.analyze(signal, sample_rate=16000)
    assert repeated['score'] == pytest.approx(result['score'], abs=1e-6)


def test_known_synthetic_speech_full_pipeline(tmp_path):
    """Known locally synthesized speech exercises inference, not detector accuracy."""
    import subprocess
    from fastapi.testclient import TestClient
    from backend.app import app

    filters = subprocess.run(['ffmpeg', '-hide_banner', '-filters'], capture_output=True, text=True, check=True).stdout
    if 'flite' not in filters:
        pytest.skip('FFmpeg was built without optional libflite speech synthesis')
    speech = tmp_path / 'known-synthetic.wav'
    subprocess.run([
        'ffmpeg', '-nostdin', '-v', 'error', '-f', 'lavfi', '-i',
        'flite=text=This recording was generated by a speech synthesizer for a VoxGuard integration test.:voice=slt',
        '-ar', '16000', str(speech),
    ], check=True)
    with TestClient(app) as client:
        response = client.post('/api/analyze', files={'file': ('synthetic.wav', speech.read_bytes(), 'audio/wav')})
    assert response.status_code == 200, response.text
    result = response.json()
    assert result['model']['name'] == 'AASIST'
    assert result['model']['loaded'] is True
    assert result['duration_seconds'] > 1
    assert 0 <= result['score'] <= 1
    assert result['classification'] == 'uncertain'
    assert result['segments']
